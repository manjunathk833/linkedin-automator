from __future__ import annotations

import json
import os
import re
from typing import Any, ClassVar

from src.resume_store.models import ResumeProfile

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_WHITELIST_PATH = os.path.join(PROJECT_ROOT, "data", "profile", "allowed_tools_whitelist.json")


def _norm_boundary(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower())


class FabricationDetector:
    """
    Zero-Cost Deterministic Post-Generation Verification Gate.
    Verifies that AI-generated bullets do not claim experience with tools or technologies
    that the candidate has never used.
    """

    KNOWN_TECH_TOOLS: ClassVar[list[str]] = [
        "Playwright",
        "Cypress",
        "Puppeteer",
        "WebdriverIO",
        "Robot Framework",
        "Protractor",
        "Golang",
        "Go",
        "C#",
        ".NET",
        "Ruby",
        "Kotlin",
        "Swift",
        "GraphQL",
        "Kubernetes",
        "DeepEval",
        "RAGAS",
        "Promptfoo",
        "Garak",
        "PyRIT",
        "OWASP LLM",
        "LangSmith",
        "Langfuse",
        "CDP",
        "FastAPI",
        "Pydantic",
        "TypeScript",
        "WireMock",
        "Pact",
    ]

    COMPANY_EXCLUSIVE_MARKERS: ClassVar[dict[str, list[str]]] = {
        "Value Labs": ["mosaic", "harness", "airline"],
        "Dunzo": ["ekam", "merchant service", "google metrics explorer"],
        "Tata Elxsi": [
            "appium",
            "testrail",
            "charles proxy",
            "burp suite",
            "ott app",
            "app store",
        ],
        "Technical Projects": [
            "deepeval",
            "ragas",
            "promptfoo",
            "garak",
            "pyrit",
            "owasp llm",
            "langsmith",
            "langfuse",
            "cdp",
            "chrome devtools protocol",
        ],
    }

    def __init__(
        self,
        profile: ResumeProfile,
        master_knowledge_bank: dict[str, Any] | None = None,
        whitelist_path: str | None = None,
    ):
        self.profile = profile
        self.knowledge_bank = master_knowledge_bank or {}
        self.whitelist_path = whitelist_path or DEFAULT_WHITELIST_PATH
        self.registry = self._load_registry()
        # Evidence-gated registry (generated by `python main.py resume sync` from the master resume)
        self.learning_roadmap: set[str] = {t.strip().lower() for t in self.registry.get("learning_roadmap", [])}
        self.tool_evidence: dict[str, list[str]] = {
            t.strip().lower(): list(b) for t, b in (self.registry.get("tool_evidence") or {}).items()
        }
        self.allowed_tools = self._build_allowed_tools_set()

    def _load_registry(self) -> dict[str, Any]:
        if not os.path.exists(self.whitelist_path):
            return {}
        try:
            with open(self.whitelist_path, "r", encoding="utf-8") as wf:
                return json.load(wf)
        except Exception:
            return {}

    def _build_allowed_tools_set(self) -> set[str]:
        """Collects all authentic tools from ResumeProfile and Master Knowledge Bank, minus roadmap tools."""
        tools = set()

        # 1. Skills Matrix
        if isinstance(self.profile.skills_matrix, dict):
            for category_tools in self.profile.skills_matrix.values():
                for t in category_tools:
                    tools.add(t.strip().lower())

        # 2. Experience History Tech Tags & Achievements
        for exp in self.profile.experience_history:
            for t in exp.tech_tags:
                tools.add(t.strip().lower())

        # 3. Master Knowledge Bank Vault & Extended Skills
        vault = self.knowledge_bank.get("master_achievements_vault", [])
        for item in vault:
            for t in item.get("tools", []):
                tools.add(t.strip().lower())

        ext_skills = self.knowledge_bank.get("extended_skills_inventory", {})
        for cat_list in ext_skills.values():
            if isinstance(cat_list, list):
                for t in cat_list:
                    tools.add(t.strip().lower())

        # 4. Canonical evidence-gated tools registry
        for wt in self.registry.get("allowed_tools", []):
            tools.add(wt.strip().lower())

        # 5. Learning-roadmap tools are blocked everywhere until they graduate via the master resume
        return tools - self.learning_roadmap

    def check_bullet(self, bullet: str) -> dict[str, Any]:
        """
        Inspects a single bullet for tool fabrication.
        Returns dict with is_valid (bool) and list of fabricated_tools (if any).
        """
        fabricated = []
        candidates = list(self.KNOWN_TECH_TOOLS)
        known_lower = {t.lower() for t in candidates}
        candidates.extend(t for t in sorted(self.learning_roadmap) if t not in known_lower)

        # Check against known external tools + learning-roadmap tools not in the allowed set
        for tool in candidates:
            tool_lower = tool.lower()
            # Strict word-boundary matching to prevent false positives (e.g. "go" in "google")
            pattern = rf"\b{re.escape(tool_lower)}\b"
            if re.search(pattern, bullet.lower()) and tool_lower not in self.allowed_tools:
                fabricated.append(tool)

        is_valid = len(fabricated) == 0
        return {
            "is_valid": is_valid,
            "fabricated_tools": fabricated,
            "bullet": bullet,
        }

    def _employer_boundaries(self) -> set[str]:
        return {
            _norm_boundary(b)
            for boundaries in self.tool_evidence.values()
            for b in boundaries
            if b != "skills" and not b.startswith("project:")
        }

    def check_boundary_evidence(self, company: str, bullet: str) -> list[str]:
        """
        Evidence-gated boundary rule: a tool may appear in a bullet for `company` only if the master
        resume shows evidence of it within that employer (or a project owned by that employer).
        Returns the list of tools lacking evidence for this boundary. Unknown boundaries are not enforced.
        """
        comp = _norm_boundary(company)
        if not self.tool_evidence or comp not in self._employer_boundaries():
            return []
        from src.resume_store.master_sync import _mentions

        vocabulary = list(self.tool_evidence)
        violations = []
        for tool, boundaries in self.tool_evidence.items():
            if not _mentions(tool, bullet, vocabulary):
                continue
            ok = any(
                _norm_boundary(b) == comp or (b.startswith("project:") and comp in _norm_boundary(b))
                for b in boundaries
            )
            if not ok:
                violations.append(tool)
        return violations

    def validate_all_bullets(self, bullets: list[str]) -> list[str]:
        """
        Filters out any fabricated bullets, logging a warning for discarded items.
        Returns only authentic, grounded bullets.
        """
        clean_bullets = []
        for bullet in bullets:
            res = self.check_bullet(bullet)
            if res["is_valid"]:
                clean_bullets.append(bullet)
            else:
                print(f"🚨 FABRICATION DETECTED & STRIPPED: Discarded bullet claiming {res['fabricated_tools']}:")
                print(f'   "{bullet[:90]}..."')
        return clean_bullets

    def check_company_contamination(self, company: str, bullet: str) -> dict[str, Any]:
        """
        Validates that a bullet assigned to a specific company does not claim achievements
        or exclusive tools that belong to another company or project boundary.
        """
        bullet_lower = bullet.lower()
        violating_companies = []
        norm_company = company.lower().replace(" ", "").replace("_", "")
        for other_comp, markers in self.COMPANY_EXCLUSIVE_MARKERS.items():
            norm_other = other_comp.lower().replace(" ", "").replace("_", "")
            if norm_other == norm_company or (norm_other in norm_company or norm_company in norm_other):
                continue
            if "project" in norm_other and ("project" in norm_company or "personal" in norm_company):
                continue
            for marker in markers:
                if marker == "harness":
                    pattern = r"(?<!test\s)\bharness\b"
                else:
                    pattern = rf"\b{re.escape(marker)}\b"
                if re.search(pattern, bullet_lower):
                    violating_companies.append(f"{other_comp} (marker: '{marker}')")
                    break

        # Evidence-gated tools: tool must have master-resume evidence within this boundary
        for tool in self.check_boundary_evidence(company, bullet):
            violating_companies.append(f"no master-resume evidence for '{tool}' at {company}")

        is_clean = len(violating_companies) == 0
        return {
            "is_clean": is_clean,
            "violating_companies": violating_companies,
            "company": company,
            "bullet": bullet,
        }

    def validate_company_bullets(self, company: str, bullets: list[str]) -> list[str]:
        """
        Filters bullets for both general tool fabrication AND cross-company contamination.
        Ensures that bullets assigned to 'company' strictly originate from that company's experience.
        """
        unfabricated = self.validate_all_bullets(bullets)
        clean_company_bullets = []
        for bullet in unfabricated:
            contam = self.check_company_contamination(company, bullet)
            if contam["is_clean"]:
                clean_company_bullets.append(bullet)
            else:
                print(
                    f"🚨 CROSS-COMPANY CONTAMINATION BLOCKED: Bullet for '{company}' claimed experience from {contam['violating_companies']}:"
                )
                print(f'   "{bullet[:90]}..."')
        return clean_company_bullets
